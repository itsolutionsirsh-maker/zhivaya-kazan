#!/usr/bin/env python3
"""Прогон игры в headless Chromium: ошибки консоли, скриншоты ключевых сцен."""
import sys, time, json, subprocess, os
from playwright.sync_api import sync_playwright

DEV = sys.argv[1] if len(sys.argv) > 1 else '/tmp/claude-0/-home-claude/7b6b1109-f7dd-5c96-b96e-10033cd54b68/scratchpad/dev'
OUT = sys.argv[2] if len(sys.argv) > 2 else '/tmp/claude-0/-home-claude/7b6b1109-f7dd-5c96-b96e-10033cd54b68/scratchpad/shots'
PORT = 8765
os.makedirs(OUT, exist_ok=True)
srv = subprocess.Popen([sys.executable, '-m', 'http.server', str(PORT), '--bind', '127.0.0.1'], cwd=DEV, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
time.sleep(0.8)
errors = []
try:
    with sync_playwright() as p:
        b = p.chromium.launch()
        pg = b.new_page(viewport={'width': 1400, 'height': 800})
        pg.on('console', lambda m: errors.append(f'[{m.type}] {m.text}') if m.type in ('error', 'warning') else None)
        pg.on('pageerror', lambda e: errors.append(f'[pageerror] {e}'))
        pg.goto(f'http://127.0.0.1:{PORT}/index.html')
        pg.wait_for_function('document.querySelector("#loading").hidden === true', timeout=60000)
        time.sleep(1.5)
        pg.screenshot(path=f'{OUT}/01_profile.png')
        pg.fill('#pName', 'Тест')
        pg.click('#startBtn')
        time.sleep(0.5)
        pg.screenshot(path=f'{OUT}/02_howto.png')
        pg.click('#howtoClose')
        time.sleep(3)
        pg.screenshot(path=f'{OUT}/03_city.png')
        stats = pg.evaluate('({walkers:walkers.length,cars:cars.length,buses:buses.length,rentals:rentals.length,own:!!ownCar,cross:world.crossings.length,fps:1})')
        print('stats', stats)
        # ночь
        pg.evaluate('clock.minutes = 23*60')
        time.sleep(1)
        pg.screenshot(path=f'{OUT}/04_night.png')
        pg.evaluate('clock.minutes = 12*60+30')
        # зум крупный
        pg.evaluate('cam.zt = 7.5')
        time.sleep(1.2)
        pg.screenshot(path=f'{OUT}/05_zoom.png')
        pg.evaluate('cam.zt = 4.5')
        # взять самокат: телепортируем к ближайшему
        pg.evaluate('''(()=>{const r=rentals.find(r=>r.kind==="scooter");if(r){player.x=r.x+1;player.y=r.y;}})()''')
        time.sleep(0.6)
        act = pg.evaluate('currentAction?currentAction.label:null')
        print('action near scooter:', act)
        pg.keyboard.press('e')
        time.sleep(0.5)
        pg.evaluate('''(()=>{const n=world.carNodes[Math.floor(world.carNodes.length/2)];const p=world.nodes[n];driveTo(p[0],p[1]);})()''')
        time.sleep(4)
        pg.screenshot(path=f'{OUT}/06_scooter.png')
        v = pg.evaluate('player.vehicle?{kind:player.vehicle.kind,speed:player.vehicle.speed,auto:!!player.vehicle.auto}:null')
        print('vehicle:', v)
        pg.keyboard.press('e')
        time.sleep(0.3)
        # машина каршеринга
        pg.evaluate('''(()=>{const r=rentals.find(r=>r.kind==="car");if(r){player.x=r.x+2;player.y=r.y;}})()''')
        time.sleep(0.5)
        print('action near car:', pg.evaluate('currentAction?currentAction.label:null'))
        pg.keyboard.press('e')
        time.sleep(0.3)
        pg.keyboard.down('w')
        time.sleep(2.5)
        pg.keyboard.up('w')
        pg.screenshot(path=f'{OUT}/07_car.png')
        print('vehicle:', pg.evaluate('player.vehicle?{kind:player.vehicle.kind,speed:player.vehicle.speed,onRoad:player.vehicle.onRoad}:null'))
        # ДТП с участием: ставим машину NPC перед нами
        pg.evaluate('''(()=>{const v=player.vehicle;const c=cars.find(c=>c.kind==="car"&&!c.crashed);c.x=v.x+v.hx*6;c.y=v.y+v.hy*6;c.hx=v.hx;c.hy=v.hy;c.state="idle";c.ttl=99;c.speed=0;c.path=null;v.speed=8;v.auto=null;})()''')
        pg.keyboard.down('w')
        time.sleep(1.5)
        pg.keyboard.up('w')
        pg.screenshot(path=f'{OUT}/08_crash.png')
        print('after crash:', pg.evaluate('({cine:!!cine,damaged:player.vehicle?player.vehicle.damaged:null,acc:accidents.length,feed:feed.slice(0,2).map(e=>e.text)})'))
        pg.evaluate('if(player.vehicle){player.vehicle.damaged=0;} ')
        time.sleep(0.3)
        pg.keyboard.press('e')
        time.sleep(0.3)
        # наезд на игрока: ставим игрока перед движущейся машиной
        pg.evaluate('''(()=>{cine=null;player.state="ok";const c=cars.find(c=>c.kind==="car"&&!c.crashed&&c.state==="drive"&&c.speed>4)||cars.find(c=>c.kind==="car"&&!c.crashed);player.x=c.x+c.hx*5;player.y=c.y+c.hy*5;c.speed=12;})()''')
        time.sleep(1.5)
        pg.screenshot(path=f'{OUT}/09_hit.png')
        print('player hit:', pg.evaluate('({state:player.state,cine:cine?cine.text:null,acc:accidents.map(a=>a.kind)})'))
        pg.evaluate('player.state="ok";cine=null;cam.zt=4.5')
        # интерьер кафе
        pg.evaluate('''(()=>{const poi=world.pois.find(p=>p.t==="cafe"&&p.n);player.x=poi.x+3;player.y=poi.y;})()''')
        time.sleep(0.5)
        print('action near cafe:', pg.evaluate('currentAction?currentAction.label:null'))
        pg.keyboard.press('e')
        time.sleep(1)
        pg.screenshot(path=f'{OUT}/10_cafe.png')
        print('interior:', pg.evaluate('interior?{kind:interior.kind,name:interior.name,npcs:interior.npcs.length,furn:interior.furn.length}:null'))
        pg.evaluate('''(()=>{const t=interior.furn.find(f=>f.spot==="table"&&!f.taken);player.ix=t.x;player.iy=t.y+1.5;})()''')
        time.sleep(0.5)
        print('action at table:', pg.evaluate('currentAction?currentAction.label:null'))
        pg.keyboard.press('e')
        time.sleep(0.4)
        pg.evaluate('player.ix=interior.door.x;player.iy=interior.door.y-0.5')
        time.sleep(0.5)
        print('action at door:', pg.evaluate('currentAction?currentAction.label:null'))
        pg.keyboard.press('e')
        time.sleep(0.5)
        print('scene:', pg.evaluate('scene'))
        # дом
        pg.evaluate('player.x=player.home.cx;player.y=player.home.cy+ (player.home.bb[3]-player.home.cy)+3')
        time.sleep(0.5)
        print('action near home:', pg.evaluate('currentAction?currentAction.label:null'))
        pg.keyboard.press('e')
        time.sleep(0.8)
        pg.screenshot(path=f'{OUT}/11_home.png')
        print('interior:', pg.evaluate('interior?interior.kind:null'))
        # магазин
        pg.evaluate('exitInterior();const poi=world.pois.find(p=>p.t==="shop"&&p.n);player.x=poi.x+3;player.y=poi.y;')
        time.sleep(0.5)
        pg.keyboard.press('e')
        time.sleep(0.8)
        pg.screenshot(path=f'{OUT}/12_shop.png')
        print('interior:', pg.evaluate('interior?interior.kind:null'))
        pg.evaluate('exitInterior()')
        # производительность
        fps = pg.evaluate('''new Promise(r=>{let n=0;const t0=performance.now();function f(){n++;if(performance.now()-t0>2000)r(n/2);else requestAnimationFrame(f);}requestAnimationFrame(f);})''')
        print('fps ~', round(fps))
        # телефон
        pg.set_viewport_size({'width': 400, 'height': 760})
        time.sleep(1)
        pg.screenshot(path=f'{OUT}/13_phone.png')
        b.close()
finally:
    srv.terminate()
print('\n'.join(errors) if errors else 'no console errors')

"""Export exact OSM district rings; no coordinate simplification.

python tools/fetch_districts.py --cache raw/districts
Use --refresh to download current relation/full snapshots from the official API.
The cache contains source evidence, not credentials. Output is deterministic.
"""
import argparse
import hashlib
import json
from pathlib import Path
from urllib.request import Request, urlopen

IDS = dict(zip(range(2133461, 2133468), (
    'aviastroitelny', 'vahitovsky', 'kirovsky', 'moskovsky',
    'novosavinovsky', 'privolzhsky', 'sovetsky')))


def rings(parts):
    """Stitch unordered/reversed ways by node identity; reject incomplete data."""
    parts = [list(p) for p in parts]
    result = []
    while parts:
        ring = parts.pop(0)
        while ring[-1] != ring[0]:
            candidates = [(i, p) for i, p in enumerate(parts)
                          if p[0] == ring[-1] or p[-1] == ring[-1]]
            if len(candidates) != 1:
                raise ValueError('Open or ambiguous boundary at node ' + str(ring[-1]))
            i, part = candidates[0]
            parts.pop(i)
            ring += (part if part[0] == ring[-1] else part[::-1])[1:]
        if len(ring) < 4:
            raise ValueError('Degenerate ring')
        result.append(ring)
    return result


def feature(raw, relation_id):
    data = json.loads(raw)
    nodes = {e['id']: [e['lon'], e['lat']] for e in data['elements'] if e['type'] == 'node'}
    ways = {e['id']: e['nodes'] for e in data['elements'] if e['type'] == 'way'}
    rel = next(e for e in data['elements'] if e['type'] == 'relation' and e['id'] == relation_id)
    if any(m['type'] != 'way' or m['role'] not in ('outer', 'inner') for m in rel['members']):
        raise ValueError('Unexpected relation members; review source manually')
    outer, inner = [[ [nodes[n] for n in ring] for ring in rings([
        ways[m['ref']] for m in rel['members'] if m['role'] == role])]
        for role in ('outer', 'inner')]
    points = [p for ring in outer for p in ring]
    return dict(id=IDS[relation_id], name=rel['tags']['name'], outer=outer, inner=inner,
                bbox=[min(p[0] for p in points), min(p[1] for p in points),
                      max(p[0] for p in points), max(p[1] for p in points)],
                source=dict(relation=relation_id, version=rel['version'],
                            timestamp=rel['timestamp'], sha256=hashlib.sha256(raw).hexdigest()))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--cache', type=Path, required=True)
    parser.add_argument('--refresh', action='store_true')
    parser.add_argument('--output', type=Path, default=Path(__file__).resolve().parents[1] / 'site/js/district-bounds.js')
    args = parser.parse_args()
    features = []
    for rel in IDS:
        file = args.cache / (str(rel) + '.json')
        if args.refresh or not file.exists():
            request = Request(f'https://api.openstreetmap.org/api/0.6/relation/{rel}/full.json',
                              headers={'User-Agent': 'ZhivayaKazan-district-export/1.0'})
            with urlopen(request, timeout=60) as response:
                raw = response.read()
            feature(raw, rel)  # validate before replacing the cache
            file.parent.mkdir(parents=True, exist_ok=True)
            file.write_bytes(raw)
        features.append(feature(file.read_bytes(), rel))
    payload = dict(attribution='© OpenStreetMap contributors', license='ODbL-1.0',
                   source='https://www.openstreetmap.org/copyright', districts=features)
    args.output.write_text('// Generated by tools/fetch_districts.py. Coordinates [longitude, latitude].\n'
                          '(function(root){const data=' + json.dumps(payload, ensure_ascii=False, separators=(',', ':'))
                          + ';if(typeof module===\'object\'&&module.exports)module.exports=data;else root.DistrictBounds=data;})(globalThis);\n', encoding='utf-8')
    for d in features:
        print(d['id'], 'rings', len(d['outer']), 'vertices', sum(map(len, d['outer'])))


if __name__ == '__main__':
    main()
